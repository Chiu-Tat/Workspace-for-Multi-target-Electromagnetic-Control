def json_load(path: Path) -> dict:
    import json

    return json.loads(path.read_text(encoding="utf-8"))


def _ablation_compact(payload: dict) -> dict:
    compact = {"protocol": payload.get("protocol")}
    for key in ("interval_original", "affine_original", "affine_hybrid"):
        if key in payload:
            compact[key] = {
                "area_fractions": payload[key].get("area_fractions"),
                "elapsed_s": payload[key].get("elapsed_s"),
                "iterations": payload[key].get("iterations"),
            }
    return compact
