def _sample_outputs(generators, offset, current_limit, n_grid=21):
    vertices = afw_tools.zonotope_vertices_2d(
        generators, offset, np.full(generators.shape[1], current_limit)
    )
    lo = vertices.min(axis=0) - 0.02
    hi = vertices.max(axis=0) + 0.02
    grid = np.array(
        np.meshgrid(np.linspace(lo[0], hi[0], n_grid), np.linspace(lo[1], hi[1], n_grid))
    ).reshape(2, -1).T
    facet = []
    for left, right in zip(vertices[:-1], vertices[1:]):
        midpoint = (left + right) / 2
        tangent = right - left
        norm = np.linalg.norm(tangent)
        if norm == 0:
            continue
        normal = np.array([tangent[1], -tangent[0]]) / norm
        # Three points per edge, separated by ten field residual tolerances.
        delta = 10 * afw_tools.DEFAULT_FIELD_TOL_T * normal
        facet.extend((midpoint - delta, midpoint, midpoint + delta))
    return np.vstack((grid, np.asarray(facet)))


def _evaluate_afw_case(spec: afw_tools.TargetSpec, active=None, current_limit=CURRENT_LIMIT_A):
    generators, offset = afw_tools.actuation_map(spec.points_coil(), active)
    radii = np.full(generators.shape[1], current_limit)
    hrep = afw_tools.zonotope_hrep(generators, offset, radii)
    samples = _sample_outputs(generators, offset, current_limit)
    residual_tol = afw_tools.DEFAULT_FIELD_TOL_T
    records = []
    for output in samples:
        hyper = afw_tools.hyperplane_membership(
            output, generators, offset, current_limit, 1e-8, hrep=hrep
        )
        independent = afw_tools.current_feasibility(
            output, generators, offset, current_limit, residual_tol
        )
        records.append({"y": output.tolist(), "hyperplane": hyper, "independent": independent})

    agreed_feasible = 0
    agreed_infeasible = 0
    disagreements = []
    solver_failures = []
    near_boundary = []
    accepted_residuals = []
    for record in records:
        hyper_f = record["hyperplane"]["feasible"]
        ind = record["independent"]
        if ind["feasible"] is None:
            solver_failures.append(record)
            continue
        slack = record["hyperplane"]["min_slack"]
        if abs(slack) < 5e-4:
            near_boundary.append(record)
        if hyper_f and ind["feasible"]:
            agreed_feasible += 1
            accepted_residuals.append(ind["residual_inf"])
        elif (not hyper_f) and (not ind["feasible"]):
            agreed_infeasible += 1
        else:
            disagreements.append(record)

    directions = np.linspace(0.0, 2 * np.pi, 16, endpoint=False)
    support_gaps = []
    radii = np.full(generators.shape[1], current_limit)
    for angle in directions:
        normal = np.array([math.cos(angle), math.sin(angle)])
        analytic = afw_tools.support_function(normal, generators, offset, radii)
        lp = afw_tools.maximize_support_lp(normal, generators, offset, current_limit)
        support_gaps.append(None if not lp["success"] else abs(analytic - lp["support"]))

    vertices = afw_tools.zonotope_vertices_2d(generators, offset, radii)
    return {
        "name": spec.name,
        "description": spec.description,
        "active_coil_indices": list(range(generators.shape[1])) if active is None else list(active),
        "hyperplane_implementation": "emns.workspace.fast.ModifiedHyperplaneShiftingMethod",
        "membership_tolerance_T": 1e-8,
        "current_residual_tolerance_T": residual_tol,
        "near_boundary_threshold_T": 5e-4,
        "sample_records": records,
        "normals": hrep[0],
        "supports": hrep[1],
        "points_coil": spec.points_coil(),
        "n_active": generators.shape[1],
        "center_T": (generators @ np.zeros(generators.shape[1]) + offset).tolist(),
        "offset_T": offset.tolist(),
        "n_samples": len(records),
        "agreed_feasible": agreed_feasible,
        "agreed_infeasible": agreed_infeasible,
        "n_disagreements": len(disagreements),
        "n_solver_failures": len(solver_failures),
        "n_near_boundary": len(near_boundary),
        "max_accepted_residual_T": max(accepted_residuals) if accepted_residuals else None,
        "max_support_gap_T": None if any(gap is None for gap in support_gaps) else max(support_gaps),
        "vertices": vertices.tolist(),
        "disagreement_examples": [
            {
                "y": item["y"],
                "hyperplane_slack": item["hyperplane"]["min_slack"],
                "independent": {
                    "feasible": item["independent"]["feasible"],
                    "residual_inf": item["independent"]["residual_inf"],
                    "status": item["independent"]["status"],
                },
            }
            for item in disagreements[:8]
        ],
    }


def run_6_2(paths: dict[str, Path]) -> dict:
    configure_matplotlib(paths["root"] / ".mplconfig")
    results = [_evaluate_afw_case(spec) for spec in AFW_CASES]
    dump_json(paths["data"] / "afw_verification.json", {"cases": results})

    # Drawn at the paper's column width (84.9 mm) so 8 pt text prints at 8 pt.
    fig, axes = plt.subplots(1, 2, figsize=(3.34, 1.75), sharex=True, sharey=True)
    titles = {"weak_interaction": "Weak interaction", "strong_interaction": "Strong interaction"}
    for axis, spec, result in zip(axes, AFW_CASES, results):
        generators, offset = afw_tools.actuation_map(spec.points_coil())
        vertices = np.asarray(result["vertices"])
        radii = np.full(generators.shape[1], CURRENT_LIMIT_A)
        hrep = afw_tools.zonotope_hrep(generators, offset, radii)
        samples = _sample_outputs(generators, offset, CURRENT_LIMIT_A)
        colours = []
        markers = []
        for output in samples:
            hyper = afw_tools.hyperplane_membership(
                output, generators, offset, CURRENT_LIMIT_A, 1e-8, hrep=hrep
            )
            independent = afw_tools.current_feasibility(
                output, generators, offset, CURRENT_LIMIT_A, afw_tools.DEFAULT_FIELD_TOL_T
            )
            if independent["feasible"] is None:
                colours.append("#888888")
                markers.append("s")
            elif hyper["feasible"] == independent["feasible"]:
                colours.append("#2e7d4f" if hyper["feasible"] else "#b85c38")
                markers.append("o" if hyper["feasible"] else "x")
            else:
                colours.append("#d4a017")
                markers.append("D")
        mt = 1e3  # plot in mT for short tick labels
        axis.fill(vertices[:, 0] * mt, vertices[:, 1] * mt, color="#9DC3E6", alpha=0.35, label="Hyperplane AFW")
        axis.plot(np.append(vertices[:, 0], vertices[0, 0]) * mt, np.append(vertices[:, 1], vertices[0, 1]) * mt, "k-", lw=0.8)
        for point, colour, marker in zip(samples, colours, markers):
            axis.scatter(point[0] * mt, point[1] * mt, c=colour, marker=marker, s=4, linewidths=0.4)
        axis.set_aspect("equal", adjustable="box")
        axis.set_xlabel(r"$b_{x,1}$ (mT)", fontsize=8, labelpad=1)
        if axis is axes[0]:
            axis.set_ylabel(r"$b_{x,2}$ (mT)", fontsize=8, labelpad=1)
        axis.tick_params(labelsize=7, pad=1.5)
        axis.locator_params(nbins=4)
        axis.set_title(titles.get(spec.name, spec.name.replace("_", " ")), fontsize=8, pad=3)
    fig.tight_layout(pad=0.3, w_pad=0.8)
    figure_path = paths["figures"] / "afw_verification.pdf"
    fig.savefig(figure_path)
    fig.savefig(figure_path.with_suffix(".png"), dpi=300)
    plt.close(fig)
    copy_to_paper(figure_path, "AFW validation.pdf")
    return {"cases": results, "figure": str(figure_path)}



def _plot_resolution_maps(paths: dict[str, Path], reports: dict, metrics: list[dict]) -> Path:
    """One compact row at the paper text width (174 mm): maps (a)-(d) and a combined plot (e)."""
    from matplotlib.gridspec import GridSpec
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch
    from analysis.sections_67.common import CLASS_COLORS, CLASS_LABELS

    levels = sorted(reports, reverse=True)
    fig = plt.figure(figsize=(6.85, 1.95))
    grid = GridSpec(1, 5, figure=fig, width_ratios=(1, 1, 1, 1, 1.75), wspace=0.16,
                    left=0.055, right=0.925, top=0.80, bottom=0.21)
    for k, width_mm in enumerate(levels):
        axis = fig.add_subplot(grid[0, k])
        _draw_region(axis, reports[width_mm], rf"({'abcd'[k]}) $\epsilon$ = {width_mm:.0f} mm")
        ticks = [-0.04, 0.0, 0.04]
        axis.set_xticks(ticks, ["\u221240", "0", "40"])
        axis.set_yticks(ticks, ["\u221240", "0", "40"] if k == 0 else [])
        axis.set_xlabel("$x$ (mm)", labelpad=1)
        axis.set_ylabel("$y$ (mm)" if k == 0 else "", labelpad=0)
        axis.tick_params(labelsize=7, pad=1.5)

    finest = [m["terminal_width_m"]["min"] * 1e3 for m in metrics]
    times = [m["elapsed_s"] for m in metrics]
    edge = {"inside": "#2e7d4f", "outside": "#c0504d", "undetermined": "#7f7f7f"}
    marker = {"inside": "o", "outside": "s", "undetermined": "^"}
    ax = fig.add_subplot(grid[0, 4])
    pos = fig.axes[-1].get_position()
    ax.set_position([pos.x0 + 0.045, pos.y0, pos.width - 0.045, pos.height])
    for c in ("inside", "outside", "undetermined"):
        ax.plot(finest, [m["area_fractions"][c] * 100 for m in metrics], marker=marker[c], ms=3.5, lw=1.1,
                color=edge[c])
    ax.set_ylim(0, 100)
    ax.set_ylabel("Area fraction (%)", labelpad=1)
    twin = ax.twinx()
    twin.plot(finest, times, "k--", marker="D", ms=3, lw=1.0)
    twin.set_ylim(0, 120)
    twin.set_ylabel("Runtime (s)", labelpad=1)
    twin.spines["right"].set_visible(True)
    for axis in (ax, twin):
        axis.set_xscale("log", base=2)
        axis.minorticks_off()
        axis.tick_params(labelsize=7, pad=1.5)
    ax.set_xticks(finest, ["6.25", "3.13", "1.56", "0.78"])
    ax.invert_xaxis()
    ax.set_xlabel("Finest width (mm)", labelpad=1)
    ax.set_title("(e) Area fraction and runtime", fontsize=8)
    handles = [Patch(facecolor=CLASS_COLORS[c], edgecolor=edge[c], label=CLASS_LABELS[c])
               for c in ("inside", "outside", "undetermined")]
    handles.append(Line2D([], [], color="k", ls="--", marker="D", ms=3, lw=1.0, label="Runtime (e)"))
    fig.legend(handles=handles, loc="upper center", ncol=4, fontsize=8, frameon=False,
               bbox_to_anchor=(0.5, 1.02), handlelength=1.8, columnspacing=1.6)
    figure_path = paths["figures"] / "resolution_study.pdf"
    fig.savefig(figure_path)
    fig.savefig(figure_path.with_suffix(".png"), dpi=300)
    plt.close(fig)
    copy_to_paper(figure_path, "resolution.pdf")
    copy_to_paper(figure_path.with_suffix(".png"), "resolution.png")
    return figure_path


def plot_resolution_figure_only(paths: dict[str, Path]) -> Path:
    """Redraw the resolution figure without re-timing or rewriting resolution_study.json."""
    configure_matplotlib(paths["root"] / ".mplconfig")
    problem = _anisotropic_problem()
    reports = {w: certify_region(problem, mode="affine_hybrid", eps=w / 1000.0, keep_boxes=True)
               for w in (8.0, 4.0, 2.0, 1.0)}
    metrics = json.loads((paths["data"] / "resolution_study.json").read_text())["metrics"]
    return _plot_resolution_maps(paths, reports, metrics)

def _draw_region(axis, report, title: str) -> None:
    for label, boxes in report.boxes.items():
        for box in boxes:
            lower, upper = box_bounds(box)
            axis.add_patch(
                Rectangle(
                    (lower[0], lower[1]),
                    upper[0] - lower[0],
                    upper[1] - lower[1],
                    linewidth=0,
                    edgecolor="none",
                    facecolor=CLASS_COLORS[label],
                    hatch=CLASS_HATCHES[label],
                    alpha=0.9,
                )
            )
    axis.set_xlim(-0.05, 0.05)
    axis.set_ylim(-0.05, 0.05)
    axis.set_aspect("equal")
    axis.set_xlabel("$x$ (m)")
    axis.set_ylabel("$y$ (m)")
    axis.set_title(title, fontsize=8)


def _anisotropic_problem(current_limit=CURRENT_LIMIT_A, active=None) -> RegionProblem:
    kwargs = dict(
        initial_box=SEARCH_BOX_M,
        z_offset=COIL_MODEL_Z_M,
        task_box=ANISOTROPIC_TASK_T,
        current_bounds=(-current_limit, current_limit),
    )
    if active is not None:
        kwargs["active_coil_indices"] = active
    return RegionProblem(**kwargs)


def run_6_3(paths: dict[str, Path]) -> dict:
    configure_matplotlib(paths["root"] / ".mplconfig")
    problem = _anisotropic_problem()
    levels_mm = (8.0, 4.0, 2.0, 1.0)
    reports = {}
    metrics = []
    for width_mm in levels_mm:
        eps = width_mm / 1000.0
        started = time.perf_counter()
        report = certify_region(problem, mode="affine_hybrid", eps=eps, keep_boxes=True)
        elapsed = time.perf_counter() - started
        payload = report_to_metrics(report, {"requested_eps_m": eps, "wall_s": elapsed})
        reports[width_mm] = report
        metrics.append(payload)
        dump_json(paths["data"] / f"resolution_hybrid_{width_mm:.0f}mm.json", payload)

    figure_path = _plot_resolution_maps(paths, reports, metrics)
    dump_json(paths["data"] / "resolution_study.json", {"metrics": metrics})
    return {"metrics": metrics, "figure": str(figure_path)}


