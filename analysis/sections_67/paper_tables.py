"""Generate manuscript tables from the reviewed numeric exports."""
from pathlib import Path
import json
import shutil
from analysis.sections_67.common import OUTPUT_ROOT, PAPER_ROOT


def generate(root=OUTPUT_ROOT, paper=PAPER_ROOT):
    writing = root / 'writing'
    writing.mkdir(exist_ok=True)
    rows = json.loads((root / 'data/afw_verification.json').read_text())['cases']
    names = {'weak_interaction': 'Weak',
             'strong_interaction': 'Strong'}
    lines = [r'% Generated by analysis.sections_67.paper_tables from afw_verification.json.',
             r'\begin{table}[t]', r'\centering\small',
             r'\caption{Agreement with an independent current LP for the weak- and strong-interaction poses (10 coils). No sample disagreed and no solve failed.}',
             r'\label{tab: afw verification}', r'\setlength{\tabcolsep}{4pt}', r'\begin{tabular}{lrrrr}', r'\toprule',
             r'Case & Samples & Both in & Both out & Max. residual (T) \\', r'\midrule']
    for row in rows:
        if row['name'] not in names:
            continue
        assert row['n_disagreements'] == 0 and row['n_solver_failures'] == 0
        val, exp = f"{row['max_accepted_residual_T']:.1e}".split('e')
        fields = [names[row['name']], *[str(row[k]) for k in ('n_samples', 'agreed_feasible', 'agreed_infeasible')],
                  rf'${val}\times10^{{{int(exp)}}}$']
        lines.append(' & '.join(fields) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    (writing/'afw_verification_table.tex').write_text('\n'.join(lines))
    metrics=json.loads((root/'data/resolution_study.json').read_text())['metrics']
    lines=[r'% Generated by analysis.sections_67.paper_tables from resolution_study.json.',
           r'\begin{table*}[t]', r'\centering\small',
           r'\caption{Affine-hybrid resolution study. Fractions use the $0.01$ m$^2$ initial search area; runtimes are single runs on an Apple M5 Pro laptop.}',
           r'\label{tab: resolution study}', r'\begin{tabular}{rrrrrr}', r'\toprule',
           r'$\epsilon$ (mm) & Finest width (mm) & TFW-in (\%) & TFW-out (\%) & Unresolved (\%) & Time (s) \\', r'\midrule']
    for row in metrics:
        fields=[f"{row['eps_m']*1000:g}", f"{row['terminal_width_m']['min']*1000:.5f}".rstrip('0'),
                *[f"{row['area_fractions'][k]*100:.3f}" for k in ('inside','outside','undetermined')], f"{row['elapsed_s']:.2f}"]
        lines.append(' & '.join(fields)+r' \\')
    lines += [r'\bottomrule',r'\end{tabular}',r'\end{table*}','']
    (writing/'resolution_metrics_table.tex').write_text('\n'.join(lines))
    macros=(r'% Generated timing macros; see resolution_study.json.'+'\n'+
            rf"\newcommand{{\ResolutionCoarseRuntime}}{{{metrics[0]['elapsed_s']:.1f}}}"+'\n'+
            rf"\newcommand{{\ResolutionFineRuntime}}{{{metrics[-1]['elapsed_s']:.1f}}}"+'\n')
    (writing/'resolution_metrics_macros.tex').write_text(macros)
    for name in ['afw_verification_table.tex','resolution_metrics_table.tex','resolution_metrics_macros.tex','coil_field_macros.tex','coil_field_table.tex']:
        if paper is not None:
            shutil.copy2(writing/name,paper/name)


if __name__ == '__main__':
    generate()
